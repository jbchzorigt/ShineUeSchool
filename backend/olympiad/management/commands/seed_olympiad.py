class Command(BaseCommand):
    help = "Олимпиадын жишээ хуваарь, үр дүнг баазад оруулна."

    def add_arguments(self, parser):
        parser.add_argument("--reset", action="store_true", help="Хуучин өгөгдлийг устгаад дахин оруулна.")

    def handle(self, *args, **options):
        if options["reset"]:
            Stage.objects.all().delete()
            Result.objects.all().delete()
        if Stage.objects.exists() or Result.objects.exists():
            self.stdout.write(self.style.WARNING("Өгөгдөл аль хэдийн байна. --reset ашиглана уу."))
            return

        stages = [
            Stage(year=year, order=i + 1, date_text=date, title=title, text=text, tags=tags)
            for year, items in SCHEDULES.items()
            for i, (date, title, text, tags) in enumerate(items)
        ]
        Stage.objects.bulk_create(stages)

        results = [
            Result(year=year, grade=grade, student=s, school=sc, score=score)
            for year, grades in RESULTS.items()
            for grade, rows in grades.items()
            for s, sc, score in rows
        ]
        Result.objects.bulk_create(results)

        self.stdout.write(self.style.SUCCESS(f"{len(stages)} шат, {len(results)} үр дүн орлоо."))
